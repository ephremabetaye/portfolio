export const SKILL_ICON_NAMES = Object.keys(SKILL_ICONS);

export function getSkillIcon(name?: string | null): LucideIcon | null {
  if (!name) return null;
  return SKILL_ICONS[name] || null;
}

/** "AudioLines" -> "Audio Lines" (for labels/tooltips). */
export function humanizeIconName(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1 $2");
}
